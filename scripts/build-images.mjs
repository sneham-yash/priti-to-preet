// Generates responsive AVIF/WebP variants (landscape + focal-point portrait crops)
// from design/source-images and writes a typed manifest for the app.
// Usage: npm run images   (re-run after replacing any source image, e.g. the oasis)
import { existsSync } from 'node:fs'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const root = path.resolve(import.meta.dirname, '..')
const srcDir = path.join(root, 'design', 'source-images')
const outDir = path.join(root, 'public', 'images')
const manifestPath = path.join(root, 'src', 'content', 'images.generated.ts')

const LANDSCAPE_WIDTHS = [640, 1280, 2048]
const PORTRAIT_WIDTHS = [480, 768, 1080]
const PORTRAIT_RATIO = 9 / 16

/** focal: [x, y] in 0..1 — the point that must survive portrait crops. */
const scenes = [
  { key: 'mountain', file: 'mountain.jpg', focal: [0.27, 0.45] },
  { key: 'ocean', file: 'ocean.jpg', focal: [0.5, 0.3], quality: { avif: 34, webp: 56 } },
  { key: 'oasis', file: 'oasis.jpg', portraitFile: 'oasis-portrait.jpg', focal: [0.5, 0.55] },
  {
    key: 'oasisEmpty',
    file: 'oasis-empty.jpg',
    portraitFile: 'oasis-empty-portrait.jpg',
    focal: [0.5, 0.55],
    optional: true,
  },
]

const DEFAULT_QUALITY = { avif: 52, webp: 74 }

const encoders = {
  avif: (img, q) => img.avif({ quality: q.avif, effort: 6 }),
  webp: (img, q) => img.webp({ quality: q.webp, effort: 6 }),
}

async function writeVariants(pipelineFactory, name, widths, maxWidth, quality) {
  const usable = widths.filter((w) => w <= maxWidth)
  if (usable.length === 0) usable.push(maxWidth)
  for (const width of usable) {
    for (const [ext, encode] of Object.entries(encoders)) {
      await encode(pipelineFactory().resize({ width, withoutEnlargement: true }), quality).toFile(
        path.join(outDir, `${name}-${width}.${ext}`),
      )
    }
  }
  return usable
}

async function processScene(scene) {
  const srcPath = path.join(srcDir, scene.file)
  if (!existsSync(srcPath)) {
    if (scene.optional) return null
    throw new Error(`Missing required source image: ${scene.file}`)
  }
  const quality = scene.quality ?? DEFAULT_QUALITY
  const meta = await sharp(srcPath).metadata()
  const width = meta.width
  const height = meta.height

  const landscapeWidths = await writeVariants(
    () => sharp(srcPath).rotate(),
    `${scene.key}-l`,
    LANDSCAPE_WIDTHS,
    width,
    quality,
  )

  // Portrait: a dedicated file if supplied, otherwise a 9:16 crop around the focal point.
  const portraitSrc = scene.portraitFile && existsSync(path.join(srcDir, scene.portraitFile))
    ? path.join(srcDir, scene.portraitFile)
    : null
  let portraitFactory
  let portraitMaxWidth
  let portraitHeight
  if (portraitSrc) {
    const pMeta = await sharp(portraitSrc).metadata()
    portraitFactory = () => sharp(portraitSrc).rotate()
    portraitMaxWidth = pMeta.width
    portraitHeight = Math.round((pMeta.height / pMeta.width) * 1000) / 1000
  } else {
    const cropWidth = Math.min(width, Math.round(height * PORTRAIT_RATIO))
    const left = Math.round(
      Math.min(Math.max(scene.focal[0] * width - cropWidth / 2, 0), width - cropWidth),
    )
    portraitFactory = () =>
      sharp(srcPath).rotate().extract({ left, top: 0, width: cropWidth, height })
    portraitMaxWidth = cropWidth
    portraitHeight = Math.round((height / cropWidth) * 1000) / 1000
  }
  const portraitWidths = await writeVariants(
    portraitFactory,
    `${scene.key}-p`,
    PORTRAIT_WIDTHS,
    portraitMaxWidth,
    quality,
  )

  return {
    key: scene.key,
    landscape: { widths: landscapeWidths, aspect: Math.round((height / width) * 1000) / 1000 },
    portrait: { widths: portraitWidths, aspect: portraitHeight, dedicated: Boolean(portraitSrc) },
    focal: scene.focal,
  }
}

await rm(outDir, { recursive: true, force: true })
await mkdir(outDir, { recursive: true })

const results = {}
for (const scene of scenes) {
  const result = await processScene(scene)
  results[scene.key] = result
  console.log(result ? `✓ ${scene.key}` : `– ${scene.key} (optional, not supplied)`)
}

const body = `// AUTO-GENERATED by scripts/build-images.mjs — do not edit by hand.
import type { ImageManifest } from './images'

export const imageManifest: ImageManifest = ${JSON.stringify(results, null, 2)}
`
await writeFile(manifestPath, body)
console.log(`Manifest written: ${path.relative(root, manifestPath)}`)
